# Explicit synthetic fixtures; never reads or replaces appdata/working.json.
source("app/R/document.R")
doc <- builder_new()
doc$document_id <- paste0("synthetic-smoke-", format(Sys.time(), "%Y%m%d-%H%M%S"))
for (fmp in c("BSAI", "GOA")) {
  for (key in names(doc$fmps[[fmp]]$sections)) doc$fmps[[fmp]]$sections[[key]]$include <- FALSE
  meta <- doc$fmps[[fmp]]$metadata
  meta$year <- "2026"
  meta$title <- paste("SYNTHETIC WORKFLOW TEST", fmp, "SAFE introduction")
  meta$contributors <- "Workflow test author"
  meta$document_date <- "21 October 2026"
  meta$catch_data_date <- "Synthetic date for validation"
  meta$source <- "Synthetic fixture generated by app/tests/render-smoke.R; no management advice"
  doc$fmps[[fmp]]$metadata <- meta
  keys <- c(paste(fmp, "_general", "_whole", c("summary", "introduction"), sep = "|"),
    paste(fmp, "pollock", "_whole", "overview", sep = "|"),
    paste(fmp, "pollock", if (fmp == "BSAI") "ebs" else "_whole",
      c("changes", "trends", "tier", "status", "apportionment"), sep = "|"))
  for (key in keys) {
    item <- builder_blank_section()
    item$text <- paste("SYNTHETIC VALIDATION FIXTURE.", builder_index(fmp)[[key]]$label,
      "contains editable test prose, not a stock-specific finding.\n\nA second paragraph checks multiline paste, wrapping and save/reload.")
    item$source <- "Synthetic workflow fixture"
    item$source_year <- "2026"
    item$reviewed <- FALSE
    doc <- builder_set(doc, key, item)
  }
  overview <- paste(fmp, "pollock", "_whole", "overview", sep = "|")
  doc$fmps[[fmp]]$sections[[overview]]$table_tsv <- "Area\tYear\tBiomass\tOFL\tABC\tTAC\tCatch\nTest area\t2025\t10000\t1500\t1100\t900\t720\nTest area\t2026\t10500\t1450\t1050\t850\t0\nTest area\t2027\t11000\t1400\t1000\tNA\tNA\nTest area\t2028\tNA\t1350\t950\tNA\tNA"
  doc$fmps[[fmp]]$sections[[overview]]$caption <- "Synthetic stock table; biomass and specifications in t"
  apportionment <- paste(fmp, "pollock", if (fmp == "BSAI") "ebs" else "_whole", "apportionment", sep = "|")
  doc$fmps[[fmp]]$sections[[apportionment]]$table_tsv <- "Area\tYear\tW\tC\tE\tOFL\tABC\tTAC\tCatch\nTest\t2026\t1\t2\t3\t100\t90\t80\t0"
  doc$fmps[[fmp]]$sections[[apportionment]]$caption <- "Synthetic wide-table layout test (t); values are invented"
  changes <- paste(fmp, "pollock", if (fmp == "BSAI") "ebs" else "_whole", "changes", sep = "|")
  doc$fmps[[fmp]]$sections[[changes]]$text <- paste(doc$fmps[[fmp]]$sections[[changes]]$text,
    "\n\nLiteral markup safety test:\n<script>alert('example')</script>\n```{r}\nstop('NEVER EXECUTE')\n```\n{{< include /etc/passwd >}}\n$math$ and \\input{secret}")
}
builder_validate(doc)
results <- lapply(c("BSAI", "GOA"), function(fmp) {
  result <- builder_render(doc, fmp, "draft", normalizePath("."))
  print(result)
  if (!all(vapply(result$results, function(x) x$ok, logical(1)))) {
    stop("A format failed. Inspect the retained render log in ", result$directory, call. = FALSE)
  }
  result
})
names(results) <- c("BSAI", "GOA")
jsonlite::write_json(results, "_output/builder/smoke-index.json", auto_unbox = TRUE, pretty = TRUE)
cat("PASS: actual synthetic BSAI and GOA HTML, Word and PDF render bundles.\n")
